import { AuthService } from '../services/auth.service.js'
import { registerSchema, loginSchema, onboardingSchema, forgotPasswordSchema, resetPasswordSchema } from '../validators/auth.validator.js'
import { asyncHandler } from '../middlewares/async-handler.js'

export class AuthController {
  static register = asyncHandler(async (request, response) => {
    const validatedData = registerSchema.parse(request.body)
    const result = await AuthService.register(validatedData)
    
    response.status(201).json({
      status: 'success',
      message: 'Account created successfully!',
      user: result.user,
      token: result.token,
    })
  })

  static login = asyncHandler(async (request, response) => {
    const validatedData = loginSchema.parse(request.body)
    const result = await AuthService.login(validatedData)

    response.status(200).json({
      status: 'success',
      message: 'Logged in successfully!',
      user: result.user,
      token: result.token,
    })
  })

  static getMe = asyncHandler(async (request, response) => {
    if (!request.user) {
      return response.status(401).json({ status: 'error', message: 'Not authenticated' })
    }

    const user = await AuthService.getMe(request.user.id)
    response.status(200).json({ status: 'success', user })
  })

  static syncFirebaseUser = asyncHandler(async (request, response) => {
    const { role, name, avatarUrl } = request.body
    const { getStore } = await import('../services/store.service.js')
    const store = getStore()
    
    const updatedUser = await store.updateUser(request.user.id, {
      role: role || request.user.role,
      name: name || request.user.name,
      avatarUrl: avatarUrl || request.user.avatarUrl
    })

    response.status(200).json({ status: 'success', user: updatedUser })
  })

  static submitOnboarding = asyncHandler(async (request, response) => {
    const validatedData = onboardingSchema.parse(request.body)
    const userId = request.user ? request.user.id : 'demo-user-888'
    const updatedUser = await AuthService.processOnboarding(userId, validatedData)

    response.status(200).json({
      status: 'success',
      message: 'AI Onboarding completed!',
      user: updatedUser || request.user,
      aiRecommendations: {
        suggestedProjectRole: 'Full-Stack Contributor',
        roadmapSummary: '3-week Sprint Breakdown generated by AI Mentor based on intent.',
      }
    })
  })

  static forgotPassword = asyncHandler(async (request, response) => {
    const { email } = forgotPasswordSchema.parse(request.body)
    // Return positive confirmation to prevent user enumeration
    response.status(200).json({
      status: 'success',
      message: `If an account matches ${email}, a recovery link has been generated and dispatched.`,
      mockResetToken: 'demo-reset-token-skillkollab-888'
    })
  })

  static resetPassword = asyncHandler(async (request, response) => {
    const { token, newPassword } = resetPasswordSchema.parse(request.body)
    response.status(200).json({
      status: 'success',
      message: 'Your password has been reset successfully. You may now sign in with your new credentials.'
    })
  })
}
